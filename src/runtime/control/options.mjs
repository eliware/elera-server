import { loadIntent } from "../../intent/model.mjs";

export function createSupervisorControlOptions(options) {
  const {
    db,
    metadata,
    managed,
    applications,
    reconciler,
    artifactStore,
    routingBundles,
    routingEvent,
    recovery,
    observationStore,
    cluster,
    nodeDataReset,
    config,
    health,
    telemetry,
    coldState,
    lifecycle,
    liveColdRecoveryProtocol,
    intentState,
    environment,
    identity,
    applyIntent,
    log,
  } = options;
  const resolve = (value) => (typeof value === "function" ? value() : value);
  return {
    db: { query: (...args) => db.query(...args) },
    metadata,
    managed,
    applications,
    reconciler,
    artifactStore,
    routingBundles,
    routingEvent,
    recovery,
    observationStore,
    lifecycle: cluster,
    nodeDataReset,
    getConfig: () => config,
    getStatus: () => health.status(),
    getTelemetry: () => telemetry.summary(),
    getTelemetryDetails: (application) => telemetry.details(application),
    getTraffic: () => ({
      drained: coldState.drain.isDraining(),
      lifecycle: lifecycle.get(),
      active: coldState.drain.active(),
      ...health.cacheInfo(),
    }),
    setDrain: (value, propagated) => coldState.clusterDrain.set(value, propagated),
    bootstrap: () => coldState.bootstrapMaria?.(),
    getColdBootstrap: () => resolve(coldState.coldBootstrapService),
    getColdEvidence: () => resolve(coldState.coldEvidence),
    getColdRecoveryProtocol: () =>
      resolve(liveColdRecoveryProtocol ?? coldState.coldRecoveryProtocol),
    getColdBootstrapLocal: () => resolve(coldState.coldBootstrapLocal),
    getActiveIntent: Object.assign(() => loadIntent(environment, identity), {
      ...intentState,
      apply: (intent) => applyIntent(intent),
    }),
    leaseCredentials: (request) => routingBundles.lease(request),
    identity,
    environment,
    log,
  };
}
