export function createControlRequestContext(request, url, response, options) {
  const {
    db,
    getStatus,
    getTraffic,
    getTelemetry,
    getTelemetryDetails,
    setDrain,
    bootstrap,
    coldBootstrap,
    getColdBootstrap,
    coldEvidence,
    getColdEvidence,
    coldBootstrapLocal,
    getColdBootstrapLocal,
    getColdRecoveryProtocol,
    lifecycle,
    getConfig,
    getActiveIntent,
    metadata,
    managed,
    auth,
    observations,
    observationStore,
    routingEvent,
    recovery,
    identity,
    environment,
    dataDir,
    internal,
  } = options;
  return {
    method: request.method,
    path: url.pathname,
    url,
    request,
    response,
    db,
    getStatus,
    getTraffic,
    getTelemetry,
    getTelemetryDetails,
    setDrain,
    bootstrap,
    coldBootstrap: coldBootstrap ?? getColdBootstrap?.(),
    coldEvidence: coldEvidence ?? getColdEvidence?.(),
    coldBootstrapLocal: coldBootstrapLocal ?? getColdBootstrapLocal,
    coldRecoveryProtocol: getColdRecoveryProtocol?.(),
    lifecycle,
    getConfig,
    getActiveIntent,
    metadata,
    managed,
    auth,
    observations,
    observationStore,
    routingEvent,
    recovery,
    identity,
    environment,
    dataDir,
    internal,
  };
}
